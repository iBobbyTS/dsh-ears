export type Translate = TranslateNS<typeof LOCALE_NAMESPACE>

export function fallbackTranslate(key: string, params?: Record<string, unknown>): string {
  const template = localeEn[key as keyof typeof localeEn] ?? key
  return params === undefined ? template : template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match)
}

const ERROR_LOCALE_KEYS: Record<EarsErrorCode, LocaleKey> = {
  [EARS_ERROR_CODES.settingsUnavailable]: 'errorSettingsUnavailable',
  [EARS_ERROR_CODES.asrAudioEmpty]: 'errorAsrAudioEmpty',
  [EARS_ERROR_CODES.asrAudioInvalid]: 'errorAsrAudioInvalid',
  [EARS_ERROR_CODES.asrAudioTooLarge]: 'errorAsrAudioTooLarge',
  [EARS_ERROR_CODES.asrNoTranscript]: 'errorAsrNoTranscript',
  [EARS_ERROR_CODES.asrUnexpected]: 'errorAsrUnexpected',
  [EARS_ERROR_CODES.browserMediaUnavailable]: 'errorBrowserMediaUnavailable',
}

export function localizedErrorText(t: Translate, code: string | undefined | null, fallback: string, params?: Readonly<Record<string, string | number>>): string {
  if (code === undefined || code === null) return fallback
  const key = ERROR_LOCALE_KEYS[code as EarsErrorCode]
  if (key === undefined) return fallback
  const template = localeZh[key]
  for (const match of template.matchAll(/\{(\w+)\}/g)) {
    if (params === undefined || !Object.prototype.hasOwnProperty.call(params, match[1])) return fallback
  }
  return t(key, params)
}

